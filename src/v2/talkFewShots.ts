/** 取当前场景最接近的 1 个示例；没有直接示例时返回 undefined（不硬凑）。 */
export function fewShotFor(scenario: ScenarioSpec | undefined): FewShot | undefined {
  if (!scenario) return undefined;
  return TALK_FEW_SHOTS.find((item) => item.scenario === scenario.name);
}

/** 把示例渲染进 Prompt 的一小段（只含 1 个示例）。 */
export function buildFewShotPrompt(fewShot: FewShot | undefined): string {
  if (!fewShot) return "";
  return [
    "下面是一组成文示例，用来说明「事实不变、表达更完整」的目标质量。",
    "只把它当作质量标杆：可以参考其详略与组织方式，但不得照抄句式，",
    "不得为了模仿示例而补充输入中没有的事实；输入比示例简单时输出应更短。",
    "",
    "【原始输入】",
    fewShot.input,
    "",
    "【目标输出】",
    fewShot.output,
  ].join("\n");
}
